import type { Question } from "../teaching/schema";

type Field = [label: string, value: number, hint: string];
function steps(
  id: string,
  prompt: string,
  fields: Field[],
  explanation: string,
): Question {
  return {
    id,
    level: "transfer",
    prompt,
    explanation,
    type: "steps",
    hint: "把题设的中间量逐个算清后再给结论。",
    fields: fields.map(([label, answer, hint]) => ({
      label,
      answer,
      hint,
      tolerance: 1e-6,
    })),
  };
}
function match(
  id: string,
  prompt: string,
  labels: string[],
  rows: [string, number][],
  explanation: string,
): Question {
  const options = labels.map((label, i) => ({ id: "opt-" + i, label }));
  return {
    id,
    level: "analysis",
    prompt,
    explanation,
    type: "match",
    hint: "检查题设假设与每个结论所需的条件。",
    options,
    rows: rows.map(([label, i]) => ({ label, answer: options[i]!.id })),
  };
}
function order(
  id: string,
  prompt: string,
  labels: string[],
  solution: number[],
  explanation: string,
): Question {
  const options = labels.map((label, i) => ({ id: "opt-" + i, label }));
  return {
    id,
    level: "analysis",
    prompt,
    explanation,
    type: "order",
    hint: "先找出产生下一步所需的输入与证据。",
    options,
    answer: solution.map((i) => options[i]!.id),
  };
}
