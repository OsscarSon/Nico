import type { TeachingBlock } from "../teaching/schema";

const example = (
  level: "application" | "challenge" | "correction" | "variant",
  title: string,
  given: string,
  goal: string,
  method: string,
  steps: string[],
  answer: string,
  check: string,
): TeachingBlock => ({
  type: "example",
  kind: "math",
  level,
  title,
  given,
  goal,
  method,
  steps: steps.map((body, i) => ({ title: "步骤 " + (i + 1), body })),
  answer,
  check,
  reveal: true,
});
const proof = (
  title: string,
  strategy: string,
  steps: [string, string][],
  check: string,
): TeachingBlock => ({
  type: "sequence",
  kind: "proof",
  title,
  strategy,
  steps: steps.map(([title, body]) => ({ title, body })),
  check,
});
